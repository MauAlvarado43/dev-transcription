let activeLocale: AppLocale = 'en';
export function resolveLocale(value: unknown): AppLocale { return value === 'es' ? 'es' : 'en'; }
export function setLocale(value: unknown): void { activeLocale = resolveLocale(value); }
export function locale(): AppLocale { return activeLocale; }
export function localeTag(): string { return activeLocale === 'es' ? 'es-MX' : 'en-US'; }
export function isMessageKey(value: unknown): value is MessageKey {
  return typeof value === 'string' && Object.hasOwn(english, value);
}
export function translate(language: AppLocale, key: MessageKey, values: TranslationValues = {}): string {
  const template = (language === 'es' ? spanish : english)[key];
  return template.replace(/\{(\w+)\}/g, (match, name: string) => String(values[name] ?? match));
}
export function t(key: MessageKey, values?: TranslationValues): string { return translate(activeLocale, key, values); }
export class LocalizedError extends Error {
  constructor(readonly key: MessageKey, readonly values?: TranslationValues) {
    super(translate('en', key, values));
    this.name = 'LocalizedError';
  }
}
export function localizeError(error: unknown): string {
  if (error instanceof LocalizedError) return t(error.key, error.values);
  if (error instanceof Error) return localizeMessage(error.message);
  return typeof error === 'string' ? localizeMessage(error) : t('unexpectedError');
}
/** Worker diagnostics stay in English; known messages are translated at the UI boundary. */
export function localizeMessage(message: string): string {
  const key = (Object.keys(english) as MessageKey[]).find(key => english[key] === message);
  if (key) return t(key);
  const segment = /^Transcribing segment (\d+) \/ (\d+)$/.exec(message);
  return segment ? t('workerSegment', { index: segment[1]!, count: segment[2]! }) : message;
}

export function countedText(key: 'videos' | 'segments' | 'transcribed', count: number): string {
  return t(`${key}${count === 1 ? 'One' : 'Other'}`, { count });
}
